export const getA2ZStats = () => {
  let totalProblems = 0;
  let solvedProblems = 0;
  
  a2zDSASheet.forEach(step => {
    step.topics.forEach(topic => {
      topic.problems.forEach(problem => {
        totalProblems += problem.count || 1;
        if (problem.solved) solvedProblems += problem.count || 1;
      });
    });
  });
  
  return { totalProblems, solvedProblems, percentage: ((solvedProblems / totalProblems) * 100).toFixed(1) };
};
